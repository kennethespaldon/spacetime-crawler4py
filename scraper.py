import re
from urllib.parse import urlparse, urljoin, urldefrag
from bs4 import BeautifulSoup
import sqlite3


MAX_CONTENT_BYTES = 5 * 1024 * 1024   # skip responses larger than ~5 MB
MIN_WORDS = 50                        # pages with fewer words are treated as low information
MAX_URL_LENGTH = 200                  # longer urls are usually generated by traps

# calendars, date archives, wiki revisions, sort orders and share links
# generate endless sets of near-identical pages
TRAP_PATTERN = re.compile(
    r"/calendar|/events?/.*\d{4}-\d{2}|\d{4}-\d{2}-\d{2}"
    r"|[?&;](ical|outlook-ical|tribe-bar-date|share|replytocom|rev|version|idx|c|o)="
    r"|[?&;]do=(diff|revisions|edit|media|index|backlink|export)"
    r"|[?&;]action=(login|edit|download|diff|history)"
)


# Save the statistics into database
def save_stats(url, word_count):
    url = urldefrag(url)[0]

    connection = sqlite3.connect("crawl_stat.db")
    cursor = connection.cursor()

    # create a table if not exists
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS pages (
            url TEXT PRIMARY KEY, 
            word_count INTEGER
        )
    """)

    # insert values
    cursor.execute("""
        INSERT OR IGNORE INTO pages (url, word_count) 
        VALUES (?,?)
    """, (url, word_count))

    connection.commit()
    connection.close()

# count word frequencies
def count_freq(words): 
    freqs = dict()

    for word in words: 
        word = word.lower()
        if word in freqs: 
            freqs[word] += 1
        else: 
            freqs[word] = 1

    return freqs


def scraper(url, resp):
    links = extract_next_links(url, resp)
    return [link for link in links if is_valid(link)]

def extract_next_links(url, resp):
    # Implementation required.
    # url: the URL that was used to get the page
    # resp.url: the actual url of the page
    # resp.status: the status code returned by the server. 200 is OK, you got the page. Other numbers mean that there was some kind of problem.
    # resp.error: when status is not 200, you can check the error here, if needed.
    # resp.raw_response: this is where the page actually is. More specifically, the raw_response has two parts:
    #         resp.raw_response.url: the url, again
    #         resp.raw_response.content: the content of the page!
    # Return a list with the hyperlinks (as strings) scrapped from resp.raw_response.content

    links = []
    visited = set()

    raw = resp.raw_response

    # redirect that was not followed: return the target so the frontier crawls it
    if 300 <= resp.status < 400:
        location = raw.headers.get("Location") if raw is not None else None
        if location:
            links.append(urldefrag(urljoin(resp.url, location))[0])
        return links

    # if the status returns other than 200, then return links
    if resp.status != 200:
        return links

    # for the case of raw_response is none, then return links
    if raw is None:
        return links

    content = raw.content

    # dead url: 200 status but no content
    if not content:
        return links

    # skip non-html responses and very large files
    content_type = raw.headers.get("Content-Type", "").lower()
    if content_type and "html" not in content_type:
        return links

    if len(content) > MAX_CONTENT_BYTES:
        return links

    try:
        # parse the content
        soup = BeautifulSoup(content, "html.parser")
    except Exception:
        return links

    # dead or low-information page: too few visible words
    for tag in soup(["script", "style"]):
        tag.decompose()

    # Remove the minimum word limit temporarily since a page fewer than 50 words could contain links
    words = re.findall(r"[a-zA-Z0-9]+", soup.get_text(" "))
    word_count = len(words)

    if is_valid(resp.url): 
        save_stats(resp.url, word_count) 

    # defragment the tags
    for tag in soup.find_all("a", href = True):
        href = tag["href"]

        # skip malformed hrefs
        try:
            abs_url = urljoin(resp.url, href)
            abs_url, frag = urldefrag(abs_url)
        except ValueError:
            continue

        # ensure links are not visited more than once using a set called "visited"
        if abs_url not in visited:
            visited.add(abs_url)
            links.append(abs_url)
    
    return links

def is_valid(url):
    # Decide whether to crawl this url or not. 
    # If you decide to crawl it, return True; otherwise return False.
    # There are already some conditions that return False.
    try:
        parsed = urlparse(url)
        if parsed.scheme not in set(["http", "https"]):
            return False

        hostname = parsed.hostname

        if hostname is None: 
            return False

        allowed_domains = (
            "ics.uci.edu",
            "cs.uci.edu",
            "informatics.uci.edu",
            "stat.uci.edu"
        )

        # filtering out the valid domains
        valid_domain = False
        for domain in allowed_domains: 
            if hostname == domain or hostname.endswith("."+domain): 
                valid_domain = True

        if not valid_domain:
            return False

        # avoid infinite traps: overly long urls
        if len(url) > MAX_URL_LENGTH:
            return False

        # avoid infinite traps: the same path segment repeated 3+ times (e.g. /a/b/a/b/a)
        segments = [s for s in parsed.path.split("/") if s]
        if any(segments.count(s) >= 3 for s in set(segments)):
            return False

        # avoid calendars, wiki revisions, sort orders and share links
        if TRAP_PATTERN.search(parsed.path.lower() + "?" + parsed.query.lower()):
            return False
        
        return not re.match(
            r".*\.(css|js|bmp|gif|jpe?g|ico"
            + r"|png|tiff?|mid|mp2|mp3|mp4"
            + r"|wav|avi|mov|mpeg|ram|m4v|mkv|ogg|ogv|pdf"
            + r"|ps|eps|tex|ppt|pptx|doc|docx|xls|xlsx|names"
            + r"|data|dat|exe|bz2|tar|msi|bin|7z|psd|dmg|iso"
            + r"|epub|dll|cnf|tgz|sha1"
            + r"|thmx|mso|arff|rtf|jar|csv"
            + r"|rm|smil|wmv|swf|wma|zip|rar|gz)$", parsed.path.lower())

    except TypeError:
        print ("TypeError for ", parsed)
        raise
